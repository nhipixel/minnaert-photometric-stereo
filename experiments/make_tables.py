"""
Generate the report's tables as LaTeX directly from results.json.

No number in the report is ever typed by hand. Tables are regenerated from the
same run that produced the shipped figures, so a rerun cannot leave a stale
value behind in the prose.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

import numpy as np

from diligent import OBJECTS
from results_io import RESULTS_DIR, load_all

TABLE_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "paper", "tables")


def _write(name, lines):
    os.makedirs(TABLE_DIR, exist_ok=True)
    path = os.path.join(TABLE_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", path)
    return path


def table1_diligent(results):
    """Per object mean angular error against the reference baseline."""
    d = results["diligent_baseline"]
    per = d["per_object"]

    lines = [
        "% Generated by experiments/make_tables.py. Do not edit by hand.",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Object & Ours & Reference & $\Delta$ \\",
        r"\midrule",
    ]
    for name in OBJECTS:
        r = per[name]
        lines.append(f"{name} & {r['mae_deg']:.2f} & {r['published_mae_deg']:.2f} "
                     f"& {r['delta_deg']:+.3f} " + r"\\")
    lines += [
        r"\midrule",
        f"Average & {d['average_mae_deg']:.2f} & {d['published_average_mae_deg']:.2f} "
        f"& {d['average_mae_deg'] - d['published_average_mae_deg']:+.3f} " + r"\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return _write("table1_diligent.tex", lines)


def macros(results):
    """
    Numbers quoted inline in the prose, as LaTeX macros.

    The report writes \\diligentAvg rather than a literal, so a rerun updates
    the sentence as well as the table.
    """
    d = results["diligent_baseline"]
    s = results.get("minnaert_sweep", {})

    per = d["per_object"]
    deltas = {k: abs(v["delta_deg"]) for k, v in per.items()}
    worst = max(deltas, key=deltas.get)
    # Agreement excluding the single object whose reference value is itself
    # disputed. Quoting only the overall maximum understates how closely the
    # other nine match.
    rest = sorted(v for k, v in deltas.items() if k != worst)

    defs = {
        "diligentAvg": f"{d['average_mae_deg']:.2f}",
        "diligentBall": f"{per['ball']['mae_deg']:.2f}",
        "diligentMaxDelta": f"{d['max_abs_delta_deg']:.3f}",
        "diligentObjects": str(len(per)),
        "diligentAgreeCount": str(len(rest)),
        "diligentAgreeDelta": f"{rest[-1]:.3f}",
        "diligentWorstObject": worst,
    }
    if s:
        defs.update({
            "sweepLights": str(s["n_lights"]),
            "sweepCond": f"{s['cond_L']:.2f}",
            "maeHapke": f"{s['mae_at_hapke_deg']:.2f}",
            "maeCollapse": f"{s['mae_at_c_zero_deg']:.2f}",
            "collapsePredicted": f"{s['collapse_limit_deg']:.2f}",
            "maeLambertian": f"{s['mae_at_lambertian_deg']:.1e}",
        })

    lines = ["% Generated by experiments/make_tables.py. Do not edit by hand."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(defs.items())]
    return _write("numbers.tex", lines)


def run():
    results = load_all()
    if not results:
        print(f"no results.json in {RESULTS_DIR}, run the experiments first")
        return None
    table1_diligent(results)
    macros(results)
    return TABLE_DIR


if __name__ == "__main__":
    run()
