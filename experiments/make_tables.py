"""
Generate the report's tables as LaTeX directly from results.json.

No number in the report is ever typed by hand. Tables are regenerated from the
same run that produced the shipped figures, so a rerun cannot leave a stale
value behind in the prose.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

import numpy as np

from diligent import OBJECTS
from results_io import RESULTS_DIR, load_all

TABLE_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "paper", "tables")


def _write(name, lines):
    os.makedirs(TABLE_DIR, exist_ok=True)
    path = os.path.join(TABLE_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", path)
    return path


# Label and citation for each estimate map tag distributed with the benchmark.
METHOD_LABELS = {
    "l2": r"Least squares baseline \cite{woodham1980}",
    "ICCV05Goldman": r"Goldman et al. \cite{goldman2005}",
    "CVPR08Alldrin": r"Alldrin et al. \cite{alldrin2008}",
    "ACCV10Wu": r"Wu et al. \cite{wu2010}",
    "CVPR10Higo": r"Higo et al. \cite{higo2010}",
    "ECCV12Shi": r"Shi et al. \cite{shi2012elevation}",
    "CVPR12Shi": r"Shi et al. \cite{shi2012biquadratic}",
    "CVPR12Ikehata": r"Ikehata et al. \cite{ikehata2012}",
    "CVPR14Ikehata": r"Ikehata et al. \cite{ikehata2014}",
}


def table1_diligent(results):
    """Per object mean angular error against the reference baseline."""
    d = results["diligent_baseline"]
    per = d["per_object"]

    lines = [
        "% Generated by experiments/make_tables.py. Do not edit by hand.",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Object & Ours & Reference & $\Delta$ \\",
        r"\midrule",
    ]
    for name in OBJECTS:
        r = per[name]
        lines.append(f"{name} & {r['mae_deg']:.2f} & {r['published_mae_deg']:.2f} "
                     f"& {r['delta_deg']:+.3f} " + r"\\")
    lines += [
        r"\midrule",
        f"Average & {d['average_mae_deg']:.2f} & {d['published_average_mae_deg']:.2f} "
        f"& {d['average_mae_deg'] - d['published_average_mae_deg']:+.3f} " + r"\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return _write("table1_diligent.tex", lines)


def table2_landscape(results):
    """Reproduced evaluation of the shipped estimate maps, ranked by average."""
    if "landscape" not in results:
        return None
    d = results["landscape"]
    per = d["per_method"]

    lines = [
        "% Generated by experiments/make_tables.py. Do not edit by hand.",
        r"\begin{tabular}{l" + "r" * (len(OBJECTS) + 1) + "}",
        r"\toprule",
        "Method & " + " & ".join(OBJECTS) + r" & avg \\",
        r"\midrule",
    ]
    for method in d["ranking_by_average"]:
        row = per[method]
        cells = " & ".join(f"{row[o]:.2f}" for o in OBJECTS)
        lines.append(f"{METHOD_LABELS[method]} & {cells} & {row['average']:.2f} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write("table2_landscape.tex", lines)


def table3_exponent(results):
    """Effective exponent and the correction study, per object."""
    if "exponent" not in results:
        return None
    d = results["exponent"]
    per = d["per_object"]

    lines = [
        "% Generated by experiments/make_tables.py. Do not edit by hand.",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Object & $c_{\mathrm{eff}}$ & LS & Oracle & Trimmed \\",
        r"\midrule",
    ]
    for name in OBJECTS:
        r = per[name]
        lines.append(
            f"{name} & {r['c_eff_median']:.2f} & {r['mae_base_deg']:.2f} "
            f"& {r['mae_oracle_pixel_deg']:.2f} & {r['mae_trimmed_deg']:.2f} " + r"\\"
        )
    lines += [
        r"\midrule",
        f"Average & & {d['avg_base_deg']:.2f} & {d['avg_oracle_pixel_deg']:.2f} "
        f"& {d['avg_trimmed_deg']:.2f} " + r"\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return _write("table3_exponent.tex", lines)


def macros(results):
    """
    Numbers quoted inline in the prose, as LaTeX macros.

    The report writes \\diligentAvg rather than a literal, so a rerun updates
    the sentence as well as the table.
    """
    d = results["diligent_baseline"]
    s = results.get("minnaert_sweep", {})

    per = d["per_object"]
    deltas = {k: abs(v["delta_deg"]) for k, v in per.items()}
    worst = max(deltas, key=deltas.get)
    # Agreement excluding the single object whose reference value is itself
    # disputed. Quoting only the overall maximum understates how closely the
    # other nine match.
    rest = sorted(v for k, v in deltas.items() if k != worst)

    defs = {
        "diligentAvg": f"{d['average_mae_deg']:.2f}",
        "diligentBall": f"{per['ball']['mae_deg']:.2f}",
        "diligentMaxDelta": f"{d['max_abs_delta_deg']:.3f}",
        "diligentObjects": str(len(per)),
        "diligentAgreeCount": str(len(rest)),
        "diligentAgreeDelta": f"{rest[-1]:.3f}",
        "diligentWorstObject": worst,
        "officialAgree": f"{d['max_agreement_with_official_deg']:.4f}",
        "degeneratePixels": str(d["total_degenerate_gt_pixels"]),
        # Two distinct quantities that are easy to conflate. The convention
        # swing is the full width between scoring undefined pixels as perfect
        # and as worst case, over the same denominator. The visible gap is what
        # Table 1 actually shows, since excluding them also changes the
        # denominator, and it equals diligentMaxDelta.
        "degenerateSwing": f"{d['total_degenerate_gt_pixels'] * 90.0 / (per[worst]['n_pixels'] + d['total_degenerate_gt_pixels']):.3f}",
        "degenerateGap": f"{abs(per[worst]['delta_deg']):.3f}",
    }
    a = results.get("ablations", {})
    if a:
        rig = a["rig_dependence"]
        geo = a["second_geometry"]
        defs.update({
            "condCorr": f"{a['conditioning']['log_log_correlation']:.3f}",
            "condMax": f"{max(a['conditioning']['cond_L']):.0f}",
            "condErrMax": f"{max(a['conditioning']['mae_deg']):.1f}",
            "lightExponent": f"{a['light_count']['fitted_exponent']:.2f}",
            "noiseExponent": f"{a['noise']['fitted_exponent_small_noise']:.2f}",
            "rigMin": f"{rig['min_deg']:.1f}",
            "rigMax": f"{rig['max_deg']:.1f}",
            "rigCount": str(rig["n_rigs"]),
            "bumpHapke": f"{geo['mae_deg'][2]:.1f}",
            "bumpTilt": f"{geo['tilt']['median_deg']:.0f}",
            "sphereTilt": f"{geo['sphere_tilt']['median_deg']:.0f}",
        })

    if s:
        defs.update({
            "sweepLights": str(s["n_lights"]),
            "sweepCond": f"{s['cond_L']:.2f}",
            "maeHapke": f"{s['mae_at_hapke_deg']:.2f}",
            "maeCollapse": f"{s['mae_at_c_zero_deg']:.2f}",
            "collapsePredicted": f"{s['collapse_limit_deg']:.2f}",
            "maeLambertian": f"{s['mae_at_lambertian_deg']:.1e}",
            "predRatioHapke": f"{s['measured_over_predicted_at_hapke']:.2f}",
            "predRatioZero": f"{s['measured_over_predicted_at_zero']:.2f}",
            "albedoSlopeHalf": f"{s['albedo_slopes']['c0.5']:.2f}",
            "albedoSlopeOne": f"{abs(s['albedo_slopes']['c1.0']):.1e}",
        })

    if "ablations" in results:
        cross = results["ablations"]["shadow_handling"].get("crossover_c")
        if cross is not None:
            defs["shadowCrossover"] = f"{cross:.2f}"

    if "landscape" in results:
        d = results["landscape"]
        defs.update({
            "landscapeBest": f"{d['best_average_deg']:.2f}",
            "landscapeWorstGain": f"{d['baseline_average_deg'] - max(d['per_method'][m]['average'] for m in d['per_method'] if m != 'l2'):.2f}",
            "landscapeBestGain": f"{d['baseline_average_deg'] - d['best_average_deg']:.2f}",
        })

    if "exponent" in results:
        d = results["exponent"]
        ceffs = [r["c_eff_median"] for r in d["per_object"].values()]
        ratios = [r["mae_base_deg"] / r["mae_rig_matched_synthetic_deg"]
                  for r in d["per_object"].values()]
        defs.update({
            "oraclePixAvg": f"{d['avg_oracle_pixel_deg']:.2f}",
            "oracleObjAvg": f"{d['avg_oracle_object_deg']:.2f}",
            "naiveAvg": f"{d['avg_naive_iterated_deg']:.2f}",
            "trimAvg": f"{d['avg_trimmed_deg']:.2f}",
            "ceffLow": f"{min(ceffs):.2f}",
            "ceffHigh": f"{max(ceffs):.2f}",
            "ceffBall": f"{d['per_object']['ball']['c_eff_median']:.2f}",
            "bridgeRatioMin": f"{min(ratios):.1f}",
            "bridgeRatioMax": f"{max(ratios):.1f}",
        })

    lines = ["% Generated by experiments/make_tables.py. Do not edit by hand."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(defs.items())]
    return _write("numbers.tex", lines)


def copy_figures():
    """
    Mirror the shipped figures next to the manuscript.

    The report references figures relative to its own folder so a clone can
    compile without the results tree, and the copy step is what keeps the two
    in step with the run that produced the recorded numbers.
    """
    import shutil

    src = os.path.join(os.path.dirname(TABLE_DIR), "..", "results", "figures")
    dst = os.path.join(os.path.dirname(TABLE_DIR), "figures")
    if not os.path.isdir(src):
        return
    os.makedirs(dst, exist_ok=True)
    for f in sorted(os.listdir(src)):
        if f.endswith(".png"):
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
            print("copied", f)


def run():
    results = load_all()
    if not results:
        print(f"no results.json in {RESULTS_DIR}, run the experiments first")
        return None
    table1_diligent(results)
    table2_landscape(results)
    table3_exponent(results)
    macros(results)
    copy_figures()
    return TABLE_DIR


if __name__ == "__main__":
    run()
